// Builds dist/plugin.js, the one file the editor loads (plugin.json's `build`): plugin.ts with @scm-js/core's codecs
// and mopaq compiled in. Until the core package with the mod formats is published, @scm-js/core is read from its
// sources (a `file:` dependency on a checkout of scm-js; README, "Before publishing"); the editor's Korean catalogue,
// which some of those modules import for their own messages, is left out as core's own build leaves it out.
//   node build.mjs [--watch]
import { build, context } from "esbuild";
import { existsSync, realpathSync } from "node:fs";
import { fileURLToPath } from "node:url";

const coreSources = fileURLToPath(new URL("./node_modules/@scm-js/core/src/index.ts", import.meta.url));
const options = {
  entryPoints: ["plugin.ts"],
  bundle: true,
  format: "esm",
  target: "es2022",
  platform: "browser",
  outfile: "dist/plugin.js",
  legalComments: "eof",
  banner: { js: "// Generated by npm run build - do not edit; the source is plugin.ts." },
  // The published package is dist/index.mjs; until then, its sources.
  alias: existsSync(coreSources) && !existsSync(new URL("./node_modules/@scm-js/core/dist/index.mjs", import.meta.url)) ? { "@scm-js/core": realpathSync(coreSources) } : {},
  plugins: [{
    name: "no-editor-catalogue",
    setup(b) {
      b.onResolve({ filter: /ko\.json$/ }, (args) => (args.importer.includes("/src/i18n/") ? { path: "catalogue", namespace: "empty" } : undefined));
      b.onLoad({ filter: /.*/, namespace: "empty" }, () => ({ contents: "export default {};", loader: "js" }));
    },
  }],
  logLevel: "info",
};

if (process.argv.includes("--watch")) await (await context(options)).watch();
else await build(options);
