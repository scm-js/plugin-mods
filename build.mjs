// Builds dist/plugin.js, the one file the editor loads (plugin.json's `build`): plugin.ts with @scm-js/core's codecs
// and mopaq compiled in.
//   node build.mjs [--watch]
import { build, context } from "esbuild";

const options = {
  entryPoints: ["plugin.ts"],
  bundle: true,
  format: "esm",
  target: "es2022",
  platform: "browser",
  outfile: "dist/plugin.js",
  legalComments: "eof",
  banner: { js: "// Generated by npm run build - do not edit; the source is plugin.ts." },
  logLevel: "info",
};

if (process.argv.includes("--watch")) await (await context(options)).watch();
else await build(options);
